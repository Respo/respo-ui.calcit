// Regenerates docs/components.md from the :doc and :examples of every
// respo-ui.comp/comp-* definition in calcit.cirru.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const lines = readFileSync(`${root}calcit.cirru`, "utf8").split("\n");
const indent = (line) => line.length - line.trimStart().length;
const dedent = (block) => {
  const width = Math.min(...block.filter((l) => l.trim()).map(indent));
  return block.map((l) => l.slice(width)).join("\n");
};

const start = lines.indexOf("    'respo-ui.comp $ %{} 'FileEntry");
let end = lines.findIndex((l, i) => i > start && /^    '\S+ \$ %\{\} 'FileEntry/.test(l));
if (end < 0) end = lines.length;

const defs = new Map();
for (let i = start; i < end; i++) {
  const head = lines[i].match(/^        '(comp-[a-z-]+) \$ %\{\} 'CodeEntry/);
  if (!head) continue;
  let j = i + 1;
  while (j < end && !/^        '/.test(lines[j])) j++;
  const block = lines.slice(i, j);
  const text = block.join("\n");
  const doc = (text.match(/\(:doc \|([^)]*)\)/) ?? text.match(/^\s+:doc "\|(.*)"$/m) ?? text.match(/^\s+:doc \|(.*)$/m))?.[1] ?? "";
  const args = text.match(new RegExp(`defcomp ${head[1]} \\(([^)]*)\\)`))?.[1] ?? "";
  const examples = [];
  block.forEach((line, k) => {
    const m = line.match(/^(\s+):examples \$ \[\] \$ quote(.*)$/);
    if (!m) return;
    const inline = m[2].trim();
    if (inline) {
      examples.push(inline.startsWith("(") && inline.endsWith(")") ? inline.slice(1, -1) : inline);
      return;
    }
    const body = [];
    for (const next of block.slice(k + 1)) {
      if (indent(next) <= m[1].length) break;
      body.push(next);
    }
    examples.push(dedent(body));
  });
  defs.set(head[1], { args, doc: doc.replaceAll("\\n", "\n").replaceAll('\\"', '"'), examples });
  i = j - 1;
}

const sections = [
  ["Form controls", ["button", "input", "textarea", "select", "checkbox", "switch", "radio-group", "field"]],
  ["Navigation", ["tabs", "breadcrumb", "pagination", "steps"]],
  ["Disclosure and hints", ["collapse", "tooltip", "kbd"]],
  ["Feedback", ["alert", "progress", "spinner", "skeleton", "empty", "badge"]],
  ["Data display", ["card", "avatar", "tag", "attributes", "divider", "time"]],
  ["Code and utilities", ["snippet", "cirru-snippet", "copy", "close", "placeholder", "catoptric-text"]],
];
const listed = new Set(sections.flatMap(([, names]) => names.map((n) => `comp-${n}`)));
const unlisted = [...defs.keys()].filter((name) => !listed.has(name));
if (unlisted.length) throw new Error(`Add to a section in scripts/gen-components-doc.mjs: ${unlisted.join(", ")}`);
const undocumented = [...defs].filter(([, { doc, examples }]) => !doc || !examples.length).map(([name]) => name);
if (undocumented.length) throw new Error(`Give these a :doc and an example: ${undocumented.join(", ")}`);

const out = [`# Components

<!-- Generated by scripts/gen-components-doc.mjs from calcit.cirru; edit the definitions' :doc and :examples instead. -->

Import components from \`respo-ui.comp\` and their option structs from \`respo-ui.schema\`.

\`\`\`cirru
ns app.comp.demo $ :require
  respo.core :refer $ defcomp div <>
  respo-ui.comp :refer $ comp-button comp-field comp-input
  respo-ui.schema :refer $ ButtonOptions FieldOptions InputOptions
\`\`\`

Every component returns \`respo.schema/Component\`. Most take an \`Option\` of a
named options struct as the last argument: pass \`Option :none\` for defaults,
or \`Option :some\` with the struct constructor. \`comp-tabs\` and
\`comp-attributes\` take the struct itself, and \`comp-time\` and
\`comp-placeholder\` take no options; the headings below show each signature.
The constructor fills every omitted \`Option\` field with \`Option :none\`, so
only write the fields you use:

\`\`\`cirru
comp-button "|Save" $ Option :some $ ButtonOptions :kind (Option :some :primary)
\`\`\`

Callbacks such as \`:on-change\` receive the new value and \`d!\`; call \`d!\` with
your app's operation tuple, for example \`d! $ :: :set-language value\`.
Run \`calcit query def respo-ui.comp/<name>\` for the full schema of any component.
`];
for (const [title, names] of sections) {
  out.push(`## ${title}\n`);
  for (const name of names.map((n) => `comp-${n}`)) {
    const { args, doc, examples } = defs.get(name);
    out.push(`### \`${name} (${args})\`\n`);
    if (doc) out.push(`${doc}\n`);
    for (const example of examples) out.push("```cirru\n" + example.replace(/\n+$/, "") + "\n```\n");
  }
}
writeFileSync(`${root}docs/components.md`, out.join("\n").replace(/\n+$/, "\n"));
console.log(`docs/components.md: ${listed.size} components`);
